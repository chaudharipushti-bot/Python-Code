len(t_value)          # Returns total number of elements.
max(t_value)          # Returns the largest element.
min(t_value)          # Returns the smallest element.
sum(t_value)          # Returns the total of all numbers.
sorted(t_value)       # Returns a sorted list from the tuple.
t_value.count(20)     # Counts occurrences of an element.
t_value.index(30)     # Returns first index of an element.
10 in t_value         # Checks if element exists.
50 not in t_value     # Checks if element does not exist.
