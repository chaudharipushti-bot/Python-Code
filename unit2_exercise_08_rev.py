# 3.8 String Methods Practice

text_value = " python programming is versatile and easy to learn "
print(f"Original Text: '{text_value}'")

print(f"(a) upper(): {text_value.upper()}")
print(f"(b) lower(): {text_value.lower()}")
print(f"(c) title(): {text_value.title()}")
print(f"(d) strip(): '{text_value.strip()}'")
print(f"(e) split(): {text_value.strip().split()}")
print(f"(f) replace spaces: {text_value.strip().replace(' ', '_')}")
print(f"(g) find('a'): {text_value.find('a')}")
